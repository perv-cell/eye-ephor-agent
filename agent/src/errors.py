"""Ошибки, которые отличают «повторить батч» от «выбросить батч»."""


class CollectorUnavailable(Exception):
    """Источник логов на этой машине сейчас прочитать нельзя."""


class RetryableSendError(Exception):
    """Сеть или сервер временно недоступны. Батч нужно вернуть в буфер."""


class PermanentSendError(Exception):
    """Сервер отверг батч. Повтор той же пачки ничего не исправит."""
